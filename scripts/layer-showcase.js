'use strict';

// LAYER SHOWCASE: one project that walks image-layer keyframes (`layer:<id>`
// tracks), so the cutout animation from Help → Layer showcase can be reviewed
// on its own.
//
//   node scripts/layer-showcase.js build [--sections move,spin] [--out <file>] [--md off]
//     writes renderer/data/layer-showcase.json and demo/layer-showcase.md
//   node scripts/layer-showcase.js list [--section spin]
//
// The walk has six sections. `move` slides a cutout on X and Y, `spin` turns
// and zooms it (uniform and non-uniform scale), `anchor` repeats the same spin
// with two rotation pivots, `fade` keys opacity, `crop` trims the picture, and
// `combo` stacks position + rotation + scale on one layer with an in/out fade
// to show the keyframes composing with the motion presets. One cue is five
// seconds, the lyric text is the same sample everywhere, and one dark plate
// sits behind the whole walk so the cutouts read against the same ground.
//
// The three cutout pictures are generated by this script (a tiny PNG encoder
// below, no canvas needed) and embedded as data URLs, so the JSON is fully
// self-contained: no network, no extra asset files.
//
// The output is generated, never hand edited: re-run this after the layer
// keyframe props (SA.glLayers.LAYER_KEY_PROPS) change.

const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const ROOT = path.resolve(__dirname, '..');
const requirePart = (relative) => require(path.join(ROOT, relative));

const project = requirePart('renderer/js/studio/project.js');
const textflow = requirePart('renderer/js/lyrics/textflow.js');

const CUE_SECONDS = 5;
// a fixed stamp keeps the generated file byte-identical on every run, so the
// build only writes when the walk itself changed
const FIXED_TIME = '2026-01-01T00:00:00.000Z';
const OUT_PATH = path.join(ROOT, 'renderer', 'data', 'layer-showcase.json');
const MD_PATH = path.join(ROOT, 'demo', 'layer-showcase.md');
// every cutout is read against the same ground: one deep plate, one label
// colour, one shared cutout size
const PLATE = '#141a2b';
const LABEL_COLOR = '#e9edf8';
const CUTOUT_SCALE = 0.3;

const SAMPLE = '切り絵キーフレーム見本 Sample';

// --- tiny PNG encoder (RGBA8, filter 0, deterministic deflate) ----------------

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buffer) {
  let crc = 0xffffffff;
  for (let i = 0; i < buffer.length; i += 1) crc = CRC_TABLE[(crc ^ buffer[i]) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'ascii');
  const tail = Buffer.alloc(4);
  tail.writeUInt32BE(crc32(Buffer.concat([Buffer.from(type, 'ascii'), data])), 0);
  return Buffer.concat([head, data, tail]);
}

function encodePng(width, height, rgba) {
  const stride = width * 4 + 1;
  const raw = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * stride] = 0;
    Buffer.from(rgba.buffer, rgba.byteOffset + y * width * 4, width * 4).copy(raw, y * stride + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(raw)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

// --- cutout pictures (160x160, flat shapes on transparency) -------------------

const PIC = 160;

function blankCanvas() {
  return new Uint8ClampedArray(PIC * PIC * 4);
}

function paint(canvas, inside, r, g, b, a) {
  for (let y = 0; y < PIC; y += 1) {
    for (let x = 0; x < PIC; x += 1) {
      if (!inside(x + 0.5, y + 0.5)) continue;
      const at = (y * PIC + x) * 4;
      canvas[at] = r;
      canvas[at + 1] = g;
      canvas[at + 2] = b;
      canvas[at + 3] = a == null ? 255 : a;
    }
  }
}

function starPath(cx, cy, outer, inner, points, rot) {
  const verts = [];
  for (let i = 0; i < points * 2; i += 1) {
    const radius = i % 2 === 0 ? outer : inner;
    const angle = rot + (i * Math.PI) / points;
    verts.push([cx + Math.cos(angle) * radius, cy + Math.sin(angle) * radius]);
  }
  return (x, y) => {
    let odd = false;
    for (let i = 0, j = verts.length - 1; i < verts.length; j = i, i += 1) {
      const [xi, yi] = verts[i];
      const [xj, yj] = verts[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) odd = !odd;
    }
    return odd;
  };
}

function circleAt(cx, cy, radius) {
  return (x, y) => (x - cx) * (x - cx) + (y - cy) * (y - cy) <= radius * radius;
}

function roundedRectAt(x0, y0, x1, y1, radius) {
  return (x, y) => {
    const cx = Math.max(x0 + radius, Math.min(x1 - radius, x));
    const cy = Math.max(y0 + radius, Math.min(y1 - radius, y));
    if (x >= x0 + radius && x <= x1 - radius) return y >= y0 && y <= y1;
    if (y >= y0 + radius && y <= y1 - radius) return x >= x0 && x <= x1;
    return (x - cx) * (x - cx) + (y - cy) * (y - cy) <= radius * radius;
  };
}

function makePictures() {
  const star = blankCanvas();
  paint(star, starPath(80, 80, 66, 27, 5, -Math.PI / 2), 255, 209, 102, 255);
  paint(star, circleAt(80, 80, 14), 20, 26, 43, 255);
  const ball = blankCanvas();
  paint(ball, circleAt(80, 84, 62), 255, 92, 122, 255);
  paint(ball, circleAt(58, 60, 18), 255, 217, 226, 255);
  const paper = blankCanvas();
  paint(paper, roundedRectAt(24, 30, 136, 130, 22), 77, 214, 193, 255);
  paint(paper, roundedRectAt(38, 44, 122, 116, 14), 20, 26, 43, 255);
  paint(paper, roundedRectAt(48, 54, 112, 106, 9), 233, 237, 248, 255);
  const encode = (canvas) => `data:image/png;base64,${encodePng(PIC, PIC, canvas).toString('base64')}`;
  return { star: encode(star), ball: encode(ball), paper: encode(paper) };
}

// --- the walk ----------------------------------------------------------------

const SECTIONS = [
  { id: 'move', label: '移動 (move)', note: '切り絵の位置だけを動かしています。X と Y に1キーずつ（開始→終了の2キー）打ち、間は直線補間です。' },
  { id: 'spin', label: '回転・拡大 (spin)', note: '回転と拡大だけを動かしています。scaleX/scaleY は scale に掛かる非等倍で、伸び縮み（squash & stretch）になります。' },
  { id: 'anchor', label: '中心点 (anchor)', note: '同じ一回転を、回転・拡大の中心だけ変えて比べます。中央 (0.5,0.5) と左上 (0,0) では軌跡が変わります。' },
  { id: 'fade', label: '透明度 (fade)', note: '不透明度だけを動かしています。シート直下の opacity がキー対象です。' },
  { id: 'crop', label: '切り抜き (crop)', note: '絵の各辺を割合で削ります。左だけのワイプと、四辺を絞るアイリスを見せます。' },
  { id: 'combo', label: '仕上げ (combo)', note: '位置・回転・拡大を重ねた切り絵に、in/out のフェードを掛けています。キーの評価値にプリセットが重なるのが分かります。' },
];

function keyTrack(from, to) {
  return [
    { t: 0, value: from, ease: 'linear' },
    { t: CUE_SECONDS, value: to, ease: 'linear' },
  ];
}

function cueId(index) {
  return `lk_${String(index + 1).padStart(3, '0')}`;
}

// One slot of the walk: which picture, which static transform, which key
// tracks (absolute values, local seconds) and which in/out motion.
function plan(pictures) {
  const base = { scale: CUTOUT_SCALE };
  const slots = [];
  const push = (section, value, detail, picture, transform, tracks, motion) => {
    slots.push({ index: slots.length + 1, section, value, detail, picture, transform: { ...base, ...(transform || {}) }, tracks: tracks || {}, motion: motion || null });
  };
  push('move', 'transform.x', 'X -0.35 → 0.35', pictures.star, {}, { 'transform.x': keyTrack(-0.35, 0.35) });
  push('move', 'transform.y', 'Y 0.30 → -0.30', pictures.ball, {}, { 'transform.y': keyTrack(0.3, -0.3) });
  push('spin', 'transform.rotate', '0° → 360°', pictures.paper, {}, { 'transform.rotate': keyTrack(0, 360) });
  push('spin', 'transform.scale', '0.15 → 0.55', pictures.star, {}, { 'transform.scale': keyTrack(0.15, 0.55) });
  push('spin', 'transform.scaleX/scaleY', 'X 0.5 → 1.6 / Y 1.6 → 0.5', pictures.ball, {}, { 'transform.scaleX': keyTrack(0.5, 1.6), 'transform.scaleY': keyTrack(1.6, 0.5) });
  push('anchor', 'transform.anchorX/anchorY', '右端 (1, 0.5) で一回転', pictures.paper, { anchorX: 1, anchorY: 0.5 }, { 'transform.rotate': keyTrack(0, 360) });
  push('anchor', 'transform.anchorX/anchorY', '左上 (0, 0) で一回転', pictures.paper, { anchorX: 0, anchorY: 0 }, { 'transform.rotate': keyTrack(0, 360) });
  push('fade', 'opacity', '1 → 0', pictures.star, {}, { opacity: keyTrack(1, 0) });
  push('crop', 'crop.l', '左 0 → 0.55', pictures.ball, {}, { 'crop.l': keyTrack(0, 0.55) });
  push(
    'crop',
    'crop.l/t/r/b',
    '四辺 0 → 0.30',
    pictures.paper,
    {},
    { 'crop.l': keyTrack(0, 0.3), 'crop.t': keyTrack(0, 0.3), 'crop.r': keyTrack(0, 0.3), 'crop.b': keyTrack(0, 0.3) }
  );
  push(
    'combo',
    'x + rotate + scale',
    'X・回転・拡大＋in/outフェード',
    pictures.star,
    {},
    { 'transform.x': keyTrack(-0.3, 0.3), 'transform.rotate': keyTrack(0, 360), 'transform.scale': keyTrack(0.25, 0.45) },
    {
      in: { type: 'fade', duration: 0.5, delay: 0, ease: 'easeOutCubic', params: {} },
      out: { type: 'fade', duration: 0.5, delay: 0, ease: 'easeInCubic', params: {} },
    }
  );
  return slots;
}

function layerName(picture, pictures) {
  if (picture === pictures.star) return 'star';
  if (picture === pictures.ball) return 'ball';
  return 'paper';
}

function cueText(index, value, detail) {
  return `${index}. ${value}（${detail}）\n${SAMPLE}`;
}

function clone(value) {
  return value == null ? value : JSON.parse(JSON.stringify(value));
}

function round(value, digits) {
  const factor = Math.pow(10, digits == null ? 3 : digits);
  return Math.round(value * factor) / factor;
}

function buildShowcase(options) {
  const opts = options || {};
  const wanted = opts.sections && opts.sections.length ? new Set(opts.sections) : null;
  const pictures = makePictures();
  const slots = plan(pictures).filter((slot) => !wanted || wanted.has(slot.section));
  if (!slots.length) throw new Error('no section matched; nothing to build');

  const cues = [];
  const markers = [];
  const layers = [];
  const keyframes = {};
  const entries = [];
  let t = 0;
  let lastSection = null;
  const sectionById = new Map(SECTIONS.map((section) => [section.id, section]));

  // one dark plate under the whole walk, so no cutout is judged against the
  // preview backdrop
  const total = round(slots.length * CUE_SECONDS);
  layers.push({
    id: 'lk_plate',
    name: 'plate',
    slot: 'background',
    type: 'solid',
    color: PLATE,
    opacity: 1,
    blend: 'normal',
    fit: 'stretch',
    radius: 0,
    enabled: true,
    start: 0,
    end: total,
    transform: { x: 0, y: 0, scale: 1, rotate: 0 },
    filter: { type: 'none', params: {} },
  });

  slots.forEach((slot, offset) => {
    const start = round(t);
    const end = round(t + CUE_SECONDS);
    const id = cueId(offset);
    const layerId = `layer_${id}`;
    if (slot.section !== lastSection) {
      lastSection = slot.section;
      markers.push({ t: start, label: sectionById.get(slot.section).label });
    }
    cues.push({
      id,
      start,
      end,
      text: cueText(slot.index, slot.value, slot.detail),
      // language-independent ids, so the Studio needs no re-labelling (same
      // shape as the backdrop showcase's meta)
      meta: { kind: 'layer-showcase', index: slot.index, section: slot.section, value: slot.value, detail: slot.detail },
    });
    const layer = {
      id: layerId,
      name: layerName(slot.picture, pictures),
      slot: 'background',
      type: 'image',
      src: slot.picture,
      fit: 'contain',
      color: '#ffffff',
      opacity: 1,
      blend: 'normal',
      radius: 0,
      enabled: true,
      start,
      end,
      transform: clone(slot.transform),
      filter: { type: 'none', params: {} },
    };
    if (slot.motion) layer.motion = clone(slot.motion);
    layers.push(layer);
    keyframes[`layer:${layerId}`] = clone(slot.tracks);
    entries.push({ index: slot.index, section: slot.section, sectionLabel: sectionById.get(slot.section).label, cueId: id, layerId, start, end, value: slot.value, detail: slot.detail, tracks: Object.keys(slot.tracks) });
    t = end;
  });

  const doc = project.create({});
  doc.meta.title = 'TelopMotion シート見本';
  doc.meta.lang = 'ja';
  doc.meta.createdAt = FIXED_TIME;
  doc.meta.updatedAt = FIXED_TIME;
  doc.script.cues = cues;
  doc.script.sourceName = 'layer-showcase.json';
  doc.markers = markers;
  // the sample stays in the middle of the frame, small enough to leave the
  // cutouts room around it
  doc.style.text.fontId = 'NotoSansJP-Regular';
  doc.style.text.size = 56;
  doc.style.text.align = 'center';
  doc.style.color = {
    fill: { kind: 'solid', value: LABEL_COLOR, alpha: 1 },
    stroke: { kind: 'solid', value: LABEL_COLOR, alpha: 1 },
  };
  textflow.apply(doc);
  doc.layers = layers;
  doc.keyframes = keyframes;

  return {
    project: doc,
    entries,
    markers,
    sections: SECTIONS.filter((section) => !wanted || wanted.has(section.id)),
    total,
  };
}

function writeFileIfChanged(file, text) {
  let current = null;
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {
    current = null;
  }
  if (current === text) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, 'utf8');
  return true;
}

function serialize(projectDoc) {
  return `${JSON.stringify(projectDoc, null, 2)}\n`;
}

function formatRange(entry) {
  return `${round(entry.start, 1)}–${round(entry.end, 1)}s`;
}

function indexMarkdown(built) {
  const lines = [];
  lines.push('# シート見本 (layer showcase)');
  lines.push('');
  lines.push(`画像シートのキーフレーム（切り絵アニメ）を 1 キューずつ並べた見本プロジェクトです。どのキューも同じサンプル文を表示し、違うのはシートの動きだけです。絵はこのスクリプトが生成した PNG（data URL 埋め込み）なので、ファイル単体で開けます。`);
  lines.push('');
  lines.push(`- 1 キュー＝${CUE_SECONDS} 秒。キーはシート開始からの相対秒で、値は絶対値（静的値を上書き）です`);
  lines.push('- シートは背景スロットの画像（`contain`）で、タイムラインのシートトラック下にキーレーンが出ます');
  lines.push('- 仕上げ（combo）だけ in/out フェード付き：キーの評価値にプリセットが重なるのが分かります');
  lines.push('- 開くには Studio の *Help → シート見本*、または *File → Open project…* を使います');
  lines.push('');
  lines.push('| # | セクション | キュー数 | 時間 |');
  lines.push('|---:|---|---:|---|');
  let order = 0;
  const rows = new Map();
  for (const entry of built.entries) {
    const row = rows.get(entry.section) || { label: entry.sectionLabel, count: 0, from: entry.start, to: entry.end };
    row.count += 1;
    row.to = entry.end;
    rows.set(entry.section, row);
  }
  for (const section of built.sections) {
    const row = rows.get(section.id);
    if (!row) continue;
    order += 1;
    lines.push(`| ${order} | ${row.label} | ${row.count} | ${round(row.from, 1)}–${round(row.to, 1)}s |`);
  }
  lines.push(`| | **合計** | **${built.entries.length}** | **${built.total}s** |`);
  lines.push('');
  lines.push('## コマンド');
  lines.push('');
  lines.push('| コマンド | 内容 |');
  lines.push('|---|---|');
  lines.push('| `npm run layer-showcase -- build` | このプロジェクトとこの一覧を再生成 |');
  lines.push('| `node scripts/layer-showcase.js list` | セクションとキューを一覧 |');
  lines.push('| `node scripts/layer-showcase.js list --section spin` | 1 セクションだけ表示 |');
  lines.push('| `npm run layer-showcase -- build --sections move,spin` | セクションを絞って生成 |');
  lines.push('');
  let sectionIndex = 0;
  for (const section of built.sections) {
    const sectionRows = built.entries.filter((entry) => entry.section === section.id);
    if (!sectionRows.length) continue;
    sectionIndex += 1;
    lines.push(`## ${sectionIndex}. ${section.label} (${section.id})`);
    lines.push('');
    if (section.note) lines.push(section.note);
    lines.push('');
    lines.push('| # | キュー | 時間 | キー | 内容 |');
    lines.push('|---:|---|---|---|---|');
    for (const entry of sectionRows) {
      lines.push(`| ${entry.index} | \`${entry.cueId}\` | ${formatRange(entry)} | \`${entry.tracks.join(', ')}\` | ${entry.detail} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

function build(options) {
  const opts = options || {};
  const out = opts.out || OUT_PATH;
  const md = opts.md === null ? null : opts.md || MD_PATH;
  const built = buildShowcase(opts);
  const migrated = project.migrate(clone(built.project));
  if (!migrated.ok) throw new Error(`generated project did not migrate: ${migrated.error}`);
  if (migrated.project.script.cues.length !== built.project.script.cues.length) {
    throw new Error(`generated project lost cues: ${migrated.project.script.cues.length}`);
  }
  const demoLayers = (migrated.project.layers || []).filter((layer) => layer && layer.type === 'image');
  if (demoLayers.length !== built.entries.length) {
    throw new Error(`generated project has ${demoLayers.length} image layers for ${built.entries.length} cues`);
  }
  for (const entry of built.entries) {
    const tracks = migrated.project.keyframes[`layer:${entry.layerId}`];
    if (!tracks) throw new Error(`generated project lost keyframes for ${entry.layerId}`);
    for (const prop of entry.tracks) {
      if (!Array.isArray(tracks[prop]) || !tracks[prop].length) throw new Error(`generated project lost ${prop} for ${entry.layerId}`);
    }
  }
  const changed = writeFileIfChanged(out, serialize(built.project));
  const mdChanged = md ? writeFileIfChanged(md, indexMarkdown(built)) : false;
  return { ...built, written: { out, changed, md, mdChanged } };
}

function parseArgs(argv) {
  const args = { positional: [], flags: {} };
  for (let i = 0; i < argv.length; i += 1) {
    const value = argv[i];
    if (value.startsWith('--')) {
      const key = value.slice(2);
      const next = argv[i + 1];
      if (!next || next.startsWith('--')) args.flags[key] = true;
      else {
        args.flags[key] = next;
        i += 1;
      }
    } else {
      args.positional.push(value);
    }
  }
  return args;
}

function parseSections(value) {
  if (typeof value !== 'string') return null;
  const ids = value.split(',').map((item) => item.trim()).filter(Boolean);
  if (!ids.length) return null;
  const known = SECTIONS.map((section) => section.id);
  for (const id of ids) {
    if (!known.includes(id)) throw new Error(`unknown section ${id} (${known.join(', ')})`);
  }
  return ids;
}

function listText(options) {
  const built = buildShowcase(options || {});
  const lines = [];
  let order = 0;
  for (const section of built.sections) {
    const rows = built.entries.filter((entry) => entry.section === section.id);
    if (!rows.length) continue;
    order += 1;
    lines.push(`${order}. ${section.label} — ${rows.length} cues`);
    for (const entry of rows) {
      lines.push(`   ${String(entry.index).padStart(3, ' ')}. ${formatRange(entry)}  ${entry.value} · ${entry.detail}`);
    }
    lines.push('');
  }
  lines.push(`total ${built.entries.length} cues, ${built.total}s`);
  return lines.join('\n');
}

function help() {
  console.log([
    'LAYER SHOWCASE: every image-layer keyframe prop in one project',
    '',
    '  node scripts/layer-showcase.js build [--sections move,spin] [--out <file>] [--md off]',
    '  node scripts/layer-showcase.js list [--section spin]',
    '',
    `sections: ${SECTIONS.map((section) => section.id).join(', ')}`,
  ].join('\n'));
}

function main(argv) {
  const args = parseArgs(argv);
  const command = args.positional[0] && args.positional[0] !== 'build' ? args.positional[0] : 'build';
  if (command === 'help') {
    help();
    return 0;
  }
  let sectionsOption = null;
  try {
    sectionsOption = parseSections(args.flags.sections || args.flags.section);
    if (command === 'list') {
      console.log(listText({ sections: sectionsOption }));
      return 0;
    }
    if (command !== 'build') {
      help();
      return 1;
    }
    const result = build({
      sections: sectionsOption,
      out: args.flags.out === true ? null : args.flags.out,
      md: args.flags.md === 'off' ? null : args.flags.md,
    });
    console.log(`layer-showcase: ${result.written.out} (${result.entries.length} cues, ${result.total}s)${result.written.changed ? '' : ' [unchanged]'}`);
    if (result.written.md) console.log(`layer-showcase: ${result.written.md}${result.written.mdChanged ? '' : ' [unchanged]'}`);
    return 0;
  } catch (error) {
    console.error(`layer-showcase: ${error.message}`);
    return 1;
  }
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

